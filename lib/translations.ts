export type TranslationKey = keyof typeof translations;

function getTranslation(key: TranslationKey, locale: AdminLocale): string {
  const entry = translations[key];
  if (!entry) return key;
  const text = entry[locale] ?? entry.en;
  return text;
}

export function useTranslations(): (key: TranslationKey) => string {
  const locale = useLocaleStore((state) => state.locale);
  return (key: TranslationKey) => getTranslation(key, locale);
}

export function getT(locale: AdminLocale) {
  return (key: TranslationKey) => getTranslation(key, locale);
}
